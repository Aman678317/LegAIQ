/**
 * Jurisiva AI Service Worker
 * Provides offline-first caching for the legal intelligence platform
 * Uses Workbox for advanced caching strategies
 */

import { precacheAndRoute, cleanupOutdatedCaches } from 'workbox-precaching';
import { registerRoute, NavigationRoute } from 'workbox-routing';
import { StaleWhileRevalidate, NetworkFirst, CacheFirst, NetworkOnly } from 'workbox-strategies';
import { ExpirationPlugin } from 'workbox-expiration';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';
import { BackgroundSyncPlugin } from 'workbox-background-sync';

// Precache all static assets generated by Next.js
precacheAndRoute(self.__WB_MANIFEST || []);

// Clean up old caches
cleanupOutdatedCaches();

// Cache names
const CACHE_NAMES = {
  static: 'jurisiva-static-v1',
  api: 'jurisiva-api-v1',
  documents: 'jurisiva-documents-v1',
  images: 'jurisiva-images-v1',
  offline: 'jurisiva-offline-v1',
};

// Maximum entries and age for caches
const MAX_ENTRIES = 100;
const MAX_AGE_SECONDS = 60 * 60 * 24 * 30; // 30 days

/**
 * Static assets - Cache First strategy
 * HTML, JS, CSS, fonts from Next.js build
 */
registerRoute(
  ({ request }) => request.destination === 'script' || request.destination === 'style' || request.destination === 'font',
  new CacheFirst({
    cacheName: CACHE_NAMES.static,
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({ maxEntries: MAX_ENTRIES, maxAgeSeconds: MAX_AGE_SECONDS }),
    ],
  })
);

/**
 * Images - Cache First with longer expiry
 */
registerRoute(
  ({ request }) => request.destination === 'image',
  new CacheFirst({
    cacheName: CACHE_NAMES.images,
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({ maxEntries: 200, maxAgeSeconds: 60 * 60 * 24 * 60 }), // 60 days
    ],
  })
);

/**
 * API GET requests - Stale While Revalidate
 * Returns cached data immediately while fetching fresh data in background
 */
registerRoute(
  ({ url }) => url.pathname.startsWith('/api/') && url.searchParams.get('_nocache') !== 'true',
  new StaleWhileRevalidate({
    cacheName: CACHE_NAMES.api,
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({ maxEntries: MAX_ENTRIES, maxAgeSeconds: 60 * 60 * 24 * 7 }), // 7 days
    ],
  }),
  'GET'
);

/**
 * API POST/PUT/DELETE - Network Only with Background Sync
 * Queue mutations when offline, replay when online
 */
const bgSyncPlugin = new BackgroundSyncPlugin('jurisiva-mutations', {
  maxRetentionTime: 24 * 60, // 24 hours
  onSync: async ({ queue }) => {
    let entry;
    while ((entry = await queue.shiftRequest())) {
      try {
        const response = await fetch(entry.request);
        if (!response.ok) {
          throw new Error(`HTTP ${response.status}`);
        }
        // Notify clients of successful sync
        self.clients.matchAll().then((clients) => {
          clients.forEach((client) => {
            client.postMessage({
              type: 'SYNC_SUCCESS',
              payload: { url: entry.request.url },
            });
          });
        });
      } catch (error) {
        // Re-queue failed request
        await queue.unshiftRequest(entry);
        throw error;
      }
    }
  },
});

registerRoute(
  ({ url, request }) => url.pathname.startsWith('/api/') && ['POST', 'PUT', 'DELETE', 'PATCH'].includes(request.method),
  new NetworkOnly({
    plugins: [bgSyncPlugin],
  }),
  'POST'
);
registerRoute(
  ({ url, request }) => url.pathname.startsWith('/api/') && ['POST', 'PUT', 'DELETE', 'PATCH'].includes(request.method),
  new NetworkOnly({
    plugins: [bgSyncPlugin],
  }),
  'PUT'
);
registerRoute(
  ({ url, request }) => url.pathname.startsWith('/api/') && ['POST', 'PUT', 'DELETE', 'PATCH'].includes(request.method),
  new NetworkOnly({
    plugins: [bgSyncPlugin],
  }),
  'DELETE'
);
registerRoute(
  ({ url, request }) => url.pathname.startsWith('/api/') && ['POST', 'PUT', 'DELETE', 'PATCH'].includes(request.method),
  new NetworkOnly({
    plugins: [bgSyncPlugin],
  }),
  'PATCH'
);

/**
 * Document files - Cache First (large files, infrequent changes)
 */
registerRoute(
  ({ url }) => url.pathname.includes('/documents/') || url.pathname.includes('/storage/'),
  new CacheFirst({
    cacheName: CACHE_NAMES.documents,
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({ maxEntries: 50, maxAgeSeconds: 60 * 60 * 24 * 30 }), // 30 days
    ],
  })
);

/**
 * Navigation requests - Network First with offline fallback
 * Try network first, fall back to cached HTML for offline navigation
 */
const navigationRoute = new NavigationRoute(
  new NetworkFirst({
    cacheName: CACHE_NAMES.offline,
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({ maxEntries: 20, maxAgeSeconds: 60 * 60 * 24 * 7 }), // 7 days
    ],
    networkTimeoutSeconds: 3,
  }),
  {
    allowlist: [/^\/dashboard/, /^\/cases/, /^\/chat/, /^\/settings/, /^\/admin/],
    denylist: [/^\/api/, /^\/_next/, /^\/static/],
  }
);
registerRoute(navigationRoute);

/**
 * Offline fallback page
 */
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAMES.offline).then((cache) => {
      return cache.addAll(['/offline.html', '/']);
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(clients.claim());
});

/**
 * Handle messages from clients
 */
self.addEventListener('message', (event) => {
  const { type, payload } = event.data || {};

  switch (type) {
    case 'SKIP_WAITING':
      self.skipWaiting();
      break;

    case 'GET_CACHE_STATUS':
      event.ports[0].postMessage({
        type: 'CACHE_STATUS',
        payload: {
          caches: Object.keys(CACHE_NAMES).map((key) => ({
            name: CACHE_NAMES[key],
            type: key,
          })),
        },
      });
      break;

    case 'CLEAR_CACHE':
      clearAllCaches().then(() => {
        event.ports[0].postMessage({ type: 'CACHE_CLEARED' });
      });
      break;

    case 'PREFETCH_CASE':
      if (payload?.caseId) {
        prefetchCaseData(payload.caseId);
      }
      break;

    default:
      break;
  }
});

/**
 * Clear all caches
 */
async function clearAllCaches() {
  const cacheNames = await caches.keys();
  await Promise.all(
    cacheNames
      .filter((name) => name.startsWith('jurisiva-'))
      .map((name) => caches.delete(name))
  );
}

/**
 * Prefetch case data for offline access
 */
async function prefetchCaseData(caseId) {
  try {
    const cache = await caches.open(CACHE_NAMES.api);
    const urls = [
      `/api/v1/cases/${caseId}`,
      `/api/v1/cases/${caseId}/documents`,
      `/api/v1/cases/${caseId}/entities`,
      `/api/v1/cases/${caseId}/timeline`,
      `/api/v1/cases/${caseId}/ownership`,
      `/api/v1/cases/${caseId}/risks`,
    ];
    await Promise.all(
      urls.map((url) =>
        fetch(url, { credentials: 'include' })
          .then((response) => {
            if (response.ok) return cache.put(url, response);
          })
          .catch(() => {}) // Ignore failures
      )
    );

    // Notify clients
    self.clients.matchAll().then((clients) => {
      clients.forEach((client) => {
        client.postMessage({
          type: 'PREFETCH_COMPLETE',
          payload: { caseId },
        });
      });
    });
  } catch (error) {
    console.error('Prefetch failed:', error);
  }
}

/**
 * Periodic sync for background updates (when supported)
 */
self.addEventListener('periodicsync', (event) => {
  if (event.tag === 'jurisiva-periodic-sync') {
    event.waitUntil(performPeriodicSync());
  }
});

async function performPeriodicSync() {
  try {
    // Sync any pending mutations
    const queue = await self.registration.sync.getTags();
    // Notify clients of sync
    self.clients.matchAll().then((clients) => {
      clients.forEach((client) => {
        client.postMessage({
          type: 'PERIODIC_SYNC_COMPLETE',
          payload: { timestamp: Date.now() },
        });
      });
    });
  } catch (error) {
    console.error('Periodic sync failed:', error);
  }
}

/**
 * Handle fetch errors for offline UX
 */
self.addEventListener('fetch', (event) => {
  // Skip non-GET requests that aren't handled by routes
  if (event.request.method !== 'GET' && !event.request.url.startsWith('/api/')) {
    return;
  }

  // For navigation requests that fail, serve offline page
  if (event.request.mode === 'navigate') {
    event.respondWith(
      fetch(event.request).catch(() => caches.match('/offline.html'))
    );
  }
});

// Notify clients when service worker is ready
self.addEventListener('controllerchange', () => {
  self.clients.matchAll().then((clients) => {
    clients.forEach((client) => {
      client.postMessage({ type: 'SW_UPDATED' });
    });
  });
});

console.log('[Jurisiva SW] Service Worker loaded');